#!/usr/bin/env node
import {
	existsSync,
	readdirSync,
	readFileSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import template from "art-template";

const root = join(fileURLToPath(new URL("..", import.meta.url)));

function artFiles(dir, out = []) {
	for (const name of readdirSync(dir)) {
		const p = join(dir, name);
		if (statSync(p).isDirectory()) artFiles(p, out);
		else if (name.endsWith(".art")) out.push(p);
	}
	return out;
}

function precompileArt() {
	const htmlRoot = join(root, "phi-assets/html");
	const outFile = join(root, "src/phi/art-compiled.ts");
	if (!existsSync(htmlRoot)) {
		console.error(`codegen: missing ${htmlRoot}`);
		process.exit(1);
	}

	const origWarn = console.warn.bind(console);
	console.warn = (...args) => {
		if (String(args[0] ?? "").includes("Template upgrade:")) return;
		origWarn(...args);
	};

	const files = artFiles(htmlRoot).sort();
	const chunks = [
		"// @ts-nocheck",
		"/* generated by scripts/codegen.mjs — do not edit */",
		"export const artFactories = {",
	];
	for (const file of files) {
		const key = relative(htmlRoot, file).replaceAll("\\", "/");
		let inner;
		try {
			inner = template
				.compile({
					filename: file,
					source: readFileSync(file, "utf8"),
					minimize: false,
					cache: false,
					debug: false,
					compileDebug: false,
					escape: true,
				})
				.toString();
		} catch (err) {
			console.error(
				`codegen: ${key}: ${err instanceof Error ? err.message : err}`,
			);
			process.exit(1);
		}
		chunks.push(`  ${JSON.stringify(key)}: function ($imports, $$options) {`);
		chunks.push(`    return (${inner})`);
		chunks.push("  },");
	}
	chunks.push("}");
	chunks.push("");

	writeFileSync(outFile, chunks.join("\n"));
	console.warn = origWarn;
	console.log(
		`codegen: ${files.length} templates → ${relative(root, outFile)}`,
	);
}

function bundleCss() {
	const cssDir = join(root, "src/phi/css");
	const outFile = join(cssDir, "bundle.ts");
	const files = readdirSync(cssDir)
		.filter((name) => name.endsWith(".css"))
		.sort();
	const lines = [
		"/* generated by scripts/codegen.mjs from src/phi/css/*.css — do not edit */",
		"/** Inlined Takumi card CSS so the renderer does not need src/phi/css on disk. */",
		"export const PHI_CSS: Record<string, string> = {",
	];
	for (const name of files) {
		const css = readFileSync(join(cssDir, name), "utf8");
		lines.push(`\t${JSON.stringify(name)}: ${JSON.stringify(css)},`);
	}
	lines.push("};", "");

	writeFileSync(outFile, lines.join("\n"));
	console.log(
		`codegen: ${files.length} stylesheets → ${relative(root, outFile)}`,
	);
}

precompileArt();
bundleCss();
